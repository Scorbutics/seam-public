// Port of src/diff/noise_filter.py — deterministic noise pre-filter (runs before any LLM).
import type { Hunk } from "./parser.js";

const _WS = /\s+/g;

const _DOC_EXTS = new Set([".md", ".markdown", ".mdx", ".rst", ".adoc", ".asciidoc", ".txt", ".rdoc", ".org"]);
const _LOCKFILES = new Set([
  "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml",
  "bun.lockb", "cargo.lock", "poetry.lock", "pipfile.lock", "uv.lock",
  "gemfile.lock", "composer.lock", "go.sum", "mix.lock", "flake.lock",
  "packages.lock.json", "podfile.lock", "pubspec.lock", "gradle.lockfile",
]);
const _GENERATED_SUFFIXES = [".min.js", ".min.css", ".map", ".pb.go", "_pb2.py",
  "_pb2_grpc.py", ".g.dart", ".freezed.dart", ".designer.cs"];
const _GENERATED_MARKER = /@generated\b|DO NOT EDIT|auto-?generated|Code generated by|generated by protoc/i;

function _basename(path: string): string {
  const parts = path.split("/");
  return (parts[parts.length - 1] ?? "").toLowerCase();
}

function _suffix(path: string): string {
  const base = _basename(path);
  const dot = base.lastIndexOf(".");
  return dot > 0 ? base.slice(dot) : "";
}

function _is_doc(path: string): boolean {
  return _DOC_EXTS.has(_suffix(path));
}

function _is_lockfile(path: string): boolean {
  return _LOCKFILES.has(_basename(path));
}

function _is_generated(hunk: Hunk): boolean {
  const name = _basename(hunk.file_path);
  if (_GENERATED_SUFFIXES.some((s) => name.endsWith(s))) return true;
  const head = hunk.text.split("\n").slice(0, 8)
    .filter((ln) => ln.startsWith("+")).map((ln) => ln.slice(1)).slice(0, 4);
  return head.some((ln) => _GENERATED_MARKER.test(ln));
}

function _strip_all_ws(s: string): string {
  return s.replace(_WS, "");
}

function _is_whitespace_or_reflow(hunk: Hunk): boolean {
  const added: string[] = [], removed: string[] = [];
  for (const line of hunk.text.split("\n")) {
    if (line.startsWith("+++") || line.startsWith("---")) continue;
    if (line.startsWith("+")) added.push(line.slice(1));
    else if (line.startsWith("-")) removed.push(line.slice(1));
  }
  if (!added.length || !removed.length) return false;
  return _strip_all_ws(added.join("")) === _strip_all_ws(removed.join(""));
}

export function classify(hunks: Hunk[]): Hunk[] {
  const remaining: Hunk[] = [];
  for (const h of hunks) {
    if (h.is_binary) { h.role = "noise"; h.rationale = "binary change — not reviewable as text"; }
    else if (h.is_rename && h.change_type === "rename" && !h.text.includes("@@")) {
      h.role = "noise"; h.rationale = "pure rename, no content change";
    } else if (_is_whitespace_or_reflow(h)) {
      h.role = "noise"; h.rationale = "whitespace / formatting / reflow only";
    } else if (_is_lockfile(h.file_path)) {
      h.role = "noise"; h.rationale = "dependency lockfile — machine-written, skim-confirm";
    } else if (_is_doc(h.file_path)) {
      h.role = "noise"; h.rationale = "documentation — ambient prose, no code logic";
    } else if (_is_generated(h)) {
      h.role = "noise"; h.rationale = "generated file — not hand-edited";
    } else remaining.push(h);
  }
  return remaining;
}
