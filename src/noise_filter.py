"""Deterministic noise pre-filter — runs before the LLM.

§9 explicitly allows heuristics + LLM, and noise's trust mechanism is literally
"confirm it really is noise", which suits a rule far better than a model. Anything
this catches never reaches the classifier (cheaper, and more trustworthy for the
one role where determinism matters).

Caught here:
  - binary changes (cannot be reviewed as text; trust delegated to the consumer)
  - pure renames with no content change
  - whitespace / formatting / indentation-only hunks, INCLUDING reflow (a line
    re-wrapped across multiple lines with the same tokens)
  - NON-CODE / machine-generated files — documentation, lockfiles, generated
    sources. These carry no code logic to review by intent and don't belong to a
    seam, so they're skim-confirm (the noise posture). Keeping them out of the LLM
    passes is the biggest token/latency win on real diffs (a doc-heavy commit can
    be hundreds of lines the model never needs to see). Conservative — file-type
    rules only, so a code hunk is never mistaken for noise.
"""

from __future__ import annotations

import re
from pathlib import PurePosixPath

from .parser import Hunk

_WS = re.compile(r"\s+")

# Documentation — ambient prose, no code logic. Skim-confirm.
_DOC_EXTS = {".md", ".markdown", ".mdx", ".rst", ".adoc", ".asciidoc", ".txt",
            ".rdoc", ".org"}
# Dependency lockfiles — machine-written, reviewed by trusting the package manager.
_LOCKFILES = {
    "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml",
    "bun.lockb", "cargo.lock", "poetry.lock", "pipfile.lock", "uv.lock",
    "gemfile.lock", "composer.lock", "go.sum", "mix.lock", "flake.lock",
    "packages.lock.json", "podfile.lock", "pubspec.lock", "gradle.lockfile",
}
# Filename suffixes that are generated/minified by tooling, not hand-edited.
_GENERATED_SUFFIXES = (".min.js", ".min.css", ".map", ".pb.go", "_pb2.py",
                       "_pb2_grpc.py", ".g.dart", ".freezed.dart", ".designer.cs")
# Markers a generator stamps near the top of a file ("@generated", "DO NOT EDIT", …).
_GENERATED_MARKER = re.compile(r"@generated\b|DO NOT EDIT|auto-?generated|"
                               r"Code generated by|generated by protoc", re.IGNORECASE)


def _basename(path: str) -> str:
    return PurePosixPath(path).name.lower()


def _is_doc(path: str) -> bool:
    return PurePosixPath(path).suffix.lower() in _DOC_EXTS


def _is_lockfile(path: str) -> bool:
    return _basename(path) in _LOCKFILES


def _is_generated(hunk: Hunk) -> bool:
    name = _basename(hunk.file_path)
    if any(name.endswith(s) for s in _GENERATED_SUFFIXES):
        return True
    # Marker in the first few added lines of the hunk (a generated-file header).
    head = [ln[1:] for ln in hunk.text.splitlines()[:8] if ln.startswith("+")][:4]
    return any(_GENERATED_MARKER.search(ln) for ln in head)


def _strip_all_ws(s: str) -> str:
    return _WS.sub("", s)


def _is_whitespace_or_reflow(hunk: Hunk) -> bool:
    """True if the added and removed sides carry the SAME tokens, differing only in
    whitespace, indentation, or where the line breaks fall (reflow).

    We compare the two sides as a whole, IN ORDER, with all whitespace removed —
    so a one-liner reflowed onto many lines (or vice-versa) still matches. This is
    deliberately order-preserving: unlike a sorted compare, a genuine REORDER of
    lines is NOT treated as noise (a reorder can change behaviour).

    Requires content on both sides — a pure add or pure delete is a real change.
    """
    added, removed = [], []
    for line in hunk.text.splitlines():
        if line.startswith("+++") or line.startswith("---"):
            continue
        if line.startswith("+"):
            added.append(line[1:])
        elif line.startswith("-"):
            removed.append(line[1:])
    if not added or not removed:
        return False
    # Concatenate each side in order, then drop ALL whitespace. Equal ⇒ the change
    # is only line-breaks / indentation / spacing.
    return _strip_all_ws("".join(added)) == _strip_all_ws("".join(removed))


def classify(hunks: list[Hunk]) -> list[Hunk]:
    """Mark obvious-noise hunks in place; return the hunks still needing the LLM."""
    remaining: list[Hunk] = []
    for h in hunks:
        if h.is_binary:
            h.role, h.rationale = "noise", "binary change — not reviewable as text"
        elif h.is_rename and h.change_type == "rename" and "@@" not in h.text:
            h.role, h.rationale = "noise", "pure rename, no content change"
        elif _is_whitespace_or_reflow(h):
            h.role, h.rationale = "noise", "whitespace / formatting / reflow only"
        elif _is_lockfile(h.file_path):
            h.role, h.rationale = "noise", "dependency lockfile — machine-written, skim-confirm"
        elif _is_doc(h.file_path):
            h.role, h.rationale = "noise", "documentation — ambient prose, no code logic"
        elif _is_generated(h):
            h.role, h.rationale = "noise", "generated file — not hand-edited"
        else:
            remaining.append(h)
    return remaining
