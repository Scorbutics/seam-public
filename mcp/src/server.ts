// Opt-in LLM data-coupling (--data-coupling llm). The deterministic floor already couples DB tables,
// HTTP routes (incl. annotation handlers ⇄ fetch/$http callers), and edge functions across the stack.
// FALLBACK-gated: the LLM key pass fires only on nodes the floor couldn't key, bounded by a per-run
// budget — so it scales on a heavy grow (the floor covers the bulk for free). Turn it ON when a question
// genuinely SPANS frameworks/stacks and the trace left a cross-stack blindspot; off by default.
const CROSS_FRAMEWORK = z.boolean().default(true)
  .describe("LLM data-coupling FLYWHEEL (on by default). On a floor-blind data edge, the LLM synthesizes a "
    + "CONSTRAINED adapter rule that is RE-EXECUTED + grounded before use, then cached to .seam/ and applied "
    + "DETERMINISTICALLY forever (LLM once → deterministic after; the flywheel learns each framework once). "
    + "Budget-capped; degrades to the deterministic floor when no LLM seam is available. Set false to force "
    + "the floor only (fully offline, no learning). Note: a COLD .seam/ can vary run-to-run on grow; warm it "
    + "in CI for byte-stable grows.");

// --spine-only: deterministic, opt-in crop of the OFF-intent band. The full closure is the default (the
// tool's philosophy — show everything, highlight, don't judge); this is a VIEW for an LLM consumer that
// pays per token. The kept/dropped split is the embedding relevance TIER (reproducible, no LLM), and it's
// HONEST — dropped seams survive as compact stubs in cluster.omitted, so nothing is silently hidden and the
// caller can re-query full. Full output is strictly more robust (the model can override the ranking); this
// trades that for fewer tokens. No-op (returns full) when embeddings are unavailable.
const SPINE_ONLY = z.boolean().default(false)
  .describe("Crop the off-intent band, keeping only spine + supporting seams (the deterministic embedding "
    + "relevance tier — reproducible, no LLM). Opt-in token/speed view; dropped seams become compact stubs "
    + "in cluster.omitted (nothing silently hidden). Default false = the full closure. No-op without embeddings.");

// A compact human-facing summary so a chat client shows something legible above the JSON.
function summarize(model: any): string {
  // Edge-set shapes — consumers (find_consumers, `set`) + dependencies (find_dependencies, `deps`): a
  // tier-counted member set + the honest noStructure negative that routes the agent to grep.
  if (model.shape === "set" || model.shape === "deps") {
    const noun = model.shape === "deps" ? "Dependencies" : "Consumers";
    const members: any[] = model.members ?? [];
    const resolved = members.filter((m) => m.provenance !== "SUGGESTED");
    const suggested = members.length - resolved.length;
    const sym = model.anchor?.symbol ?? "?";
    const recalled: any[] = model.recalled ?? [];
    const recalledLine = recalled.length
      ? `\n${recalled.length} recalled (name-grounded, UNVERIFIED):\n`
        + recalled.slice(0, 12).map((m) => `• ${m.symbol} (${m.file}:${m.line})`).join("\n")
        + (recalled.length > 12 ? `\n…and ${recalled.length - 12} more` : "")
      : "";
    if (model.noStructure)
      return `${noun} of ${sym}: none resolved (${model.reason}).\n`
        + (model.reason === "opaque"
          ? "Edges exist but none resolve structurally — this is a grep/LSP question."
          : model.shape === "deps" ? "A leaf — it uses nothing resolvable."
          : "No caller in the repo — an entry point, dead code, or dispatched-only.")
        + recalledLine;
    const lines = resolved.slice(0, 12).map((m) => `• ${m.symbol} (${m.file}:${m.line}) [${m.provenance}]`).join("\n");
    const extra = resolved.length > 12 ? `\n…and ${resolved.length - 12} more` : "";
    return `${noun} of ${sym}: ${resolved.length} resolved`
      + (suggested ? `, ${suggested} suggested` : "")
      + ((model.unresolved ?? []).length ? `, ${model.unresolved.length} unresolved (grep these)` : "")
      + `\n${lines}${extra}${recalledLine}`;
  }
  // Refactor-facts bundle (refactor_facts) — impact + dependencies + contract, composed.
  if (model.shape === "refactor") {
    const sym = model.anchor?.symbol ?? "?";
    const im = model.impact ?? {}, dep = model.dependencies ?? {}, ct = model.contract ?? {};
    return `Refactor facts for ${sym}: impact ${im.total ?? 0} across ${im.fileCount ?? 0} file(s)`
      + ((im.gaps ?? []).length ? ` (${im.gaps.length} opaque gap(s))` : "")
      + `, ${(dep.members ?? []).length} dependency(ies), contract ${(ct.provides ?? []).length} provided/`
      + `${(ct.unusedExports ?? []).length} unused.\nThe facts to plan a change to ${sym} — the change PLAN over them is yours to make.`;
  }
  // Impact shape (impact_of) — transitive blast radius: count, surface, gaps.
  if (model.shape === "impact") {
    const sym = model.anchor?.symbol ?? "?";
    if (model.noStructure) return `Impact of ${sym}: isolated — no resolved consumers (${model.reason})`
      + ((model.gaps ?? []).length ? `, but ${model.gaps.length} opaque caller(s) to verify.` : ".");
    const top = (model.files ?? []).slice(0, 10).map((f: any) => `• ${f.file} (${f.count})`).join("\n");
    return `Impact of ${sym}: ${model.total} symbol(s) across ${model.fileCount} file(s)`
      + `, ${(model.surface ?? []).length} at the surface`
      + ((model.gaps ?? []).length ? `, ${model.gaps.length} opaque gap(s)` : "")
      + (model.truncated ? " (truncated — impact ≥ shown)" : "") + `\n${top}`;
  }
  // Comparison shape (compare_symbols) — shared / A-only / B-only dependencies + similarity.
  if (model.shape === "comparison") {
    const aS = model.a?.symbol ?? "A", bS = model.b?.symbol ?? "B";
    if (model.noStructure) return `${aS} vs ${bS}: neither has resolved dependencies — nothing to compare.`;
    const names = (xs: any[]) => xs.slice(0, 10).map((d: any) => d.symbol).join(", ");
    return `${aS} vs ${bS} (by deps): ${(model.shared ?? []).length} shared, ${(model.aOnly ?? []).length} ${aS}-only, `
      + `${(model.bOnly ?? []).length} ${bS}-only — similarity ${Math.round((model.similarity ?? 0) * 100)}%\n`
      + `shared: ${names(model.shared ?? []) || "—"}\n${aS}-only: ${names(model.aOnly ?? []) || "—"}\n${bS}-only: ${names(model.bOnly ?? []) || "—"}`;
  }
  // Neighborhood shape (subsystem) — core/periphery files + cohesion + boundary cut.
  if (model.shape === "neighborhood") {
    if (model.noStructure) return `${model.anchor?.symbol ?? "?"}: isolated — no cohesive subsystem.`;
    const head = `Subsystem around ${model.anchor?.symbol ?? "?"}: ${(model.coreFiles ?? []).length} core`
      + ((model.peripheryFiles ?? []).length ? ` + ${model.peripheryFiles.length} periphery` : "")
      + `, cohesion ${Math.round((model.cohesion ?? 0) * 100)}%, boundary cut ${model.boundaryCut}`;
    const core = (model.members ?? []).filter((m: any) => m.core).slice(0, 10)
      .map((m: any) => `• ${m.file} (in ${m.internal}, out ${m.external})`).join("\n");
    return `${head}${core ? `\n${core}` : ""}`;
  }
  // Contract shape (module_contract) — the inbound/outbound cut + coupling pair.
  if (model.shape === "contract") {
    if (model.noStructure) return `${model.module}: no exported members — no contract.`;
    const head = `${model.module}: provides ${(model.provides ?? []).length} (used), ${(model.unusedExports ?? []).length} unused; `
      + `depends ${(model.depends ?? []).length} | fan-in ${model.afferent}, fan-out ${model.efferent}`;
    const prov = (model.provides ?? []).slice(0, 8).map((p: any) => `• ${p.symbol} ← ${p.consumerCount} consumer(s)`).join("\n");
    const unused = (model.unusedExports ?? []).length ? `\nunused exports: ${model.unusedExports.join(", ")}` : "";
    return `${head}${prov ? `\n${prov}` : ""}${unused}`;
  }
  // Reachability shape (can_reach) — verdict + witness path, with the three distinct negatives.
  if (model.shape === "reaches") {
    const f = model.from?.symbol ?? "?", t = model.to?.symbol ?? "?";
    if (model.reachable)
      return `${f} → ${t}: REACHABLE in ${(model.path?.length ?? 1) - 1} hop(s) — proven path:\n`
        + (model.path ?? []).map((s: any) => `• ${s.symbol} (${s.file}:${s.line})`).join("\n");
    return `${f} → ${t}: ${model.reason === "exhausted" ? "NOT FOUND within budget (INCONCLUSIVE — raise maxHops)"
      : model.reason === "no-out-edges" ? `undefined — ${f} has no resolved dependencies`
      : "UNREACHABLE (searched the whole resolved dependency closure)"} [${model.hops} hop(s) explored]`;
  }
  const clusters = model.clusters ?? [];
  const seams = clusters.reduce((n: number, c: any) => n + (c.seams?.length ?? 0), 0);
  const roleCounts: Record<string, number> = {};
  for (const c of clusters) for (const s of c.seams ?? []) for (const h of s.hunks ?? [])
    roleCounts[h.role] = (roleCounts[h.role] ?? 0) + 1;
  for (const h of [...(model.tests ?? []), ...(model.noise ?? [])]) roleCounts[h.role] = (roleCounts[h.role] ?? 0) + 1;
  const roles = Object.entries(roleCounts).map(([r, n]) => `${r}=${n}`).join("  ");
  const intents = clusters.map((c: any) => `• ${c.intent}`).join("\n");
  const head = `${clusters.length} cluster(s), ${seams} seam(s)   [${roles}]`;
  const extras = [
    model.mode ? `mode=${model.mode}` : "",
    model.anchor ? `anchor=${model.anchor}` : "",
    model.resolutionQuality ? `resolution=${model.resolutionQuality}` : "",
    model.usage ? `${model.usage.calls} LLM call(s)` : "",
  ].filter(Boolean).join("  ");
  // --review-impact annotations (decompose_diff impact:true) — lead with the cross-stack hook, then the
  // external-impact tally; this is the part no diff-only tool can produce.
  const cross = clusters.flatMap((c: any) => c.seams ?? []).flatMap((s: any) => s.impact?.crossStack ?? []);
  const extImpact = clusters.flatMap((c: any) => c.seams ?? []).flatMap((s: any) => s.impact?.external ?? []);
  const impactLines: string[] = [];
  if (cross.length) {
    impactLines.push("⚠ cross-stack (changed here, NOT in this PR — verify):");
    for (const c of cross.slice(0, 8)) impactLines.push(`  ${c.relation} of '${c.key}' → ${c.symbol} (${c.file})`);
  }
  if (extImpact.length) impactLines.push(`impact: ${extImpact.length} symbol(s) affected outside this PR`);
  const impactBlock = impactLines.length ? `\n\n${impactLines.join("\n")}` : "";
  const so = model.spineOnly;
  const spineLine = so
    ? (so.unavailable ? "\n\nspine-only requested but embeddings unavailable → full closure returned."
       : `\n\nspine-only: cropped ${so.omitted} off-intent seam(s) (kept spine+supporting; dropped seams are stubs in cluster.omitted — re-query without spineOnly for full).`)
    : "";
  return `${head}${extras ? `   (${extras})` : ""}\n${intents}${impactBlock}${adapterStatus(model)}${spineLine}`;
}

// Explicit learned-adapter status for the human summary — "X used, Y newly learned", with names + where
// they live (repo `.seam/` vs the shared store). The engine stamps `model.adapters` (the run ledger); we
// surface it so a flywheel run REPORTS the compounding asset it touched, and so a re-run that learns more
// (rather than reusing) is immediately visible. Empty ledger → nothing (a pure deterministic-floor run).
function adapterStatus(model: any): string {
  const ad = model.adapters;
  if (!ad || (!ad.used?.length && !ad.learned?.length)) return "";
  const names = (xs: string[]) => xs.slice(0, 8).join(", ") + (xs.length > 8 ? `, …+${xs.length - 8}` : "");
  const usedNames = (ad.used ?? []).map((u: any) => u.name);
  const fromShared = (ad.used ?? []).some((u: any) => u.scope === "shared");
  const lines = [`learned adapters: ${usedNames.length} used` + (usedNames.length ? ` (${names(usedNames)})` : "")
    + `, ${(ad.learned ?? []).length} newly learned` + (ad.learned?.length ? ` (${names(ad.learned)})` : "")];
  lines.push(`  cached in <repo>/.seam/key-*.json${fromShared ? " + the shared adapter store" : ""}` +
    ((ad.learned ?? []).length ? " — re-run to confirm 0 newly learned (fully warm); promote with `seam-adapters`" : ""));
  return `\n\n${lines.join("\n")}`;
}

// The engine emits a one-line timing summary on stderr at the end of a run (see core/progress.ts).
// Parse it so the agent can tell the user how long each phase took. Contract marker — keep in sync.
const TIMING_PREFIX = "@@SEAM_TIMING@@";
function parseTiming(stderr: string): { totalMs: number; phases: { phase: string; durationMs: number }[] } | null {
  const line = stderr.split("\n").reverse().find((l) => l.startsWith(TIMING_PREFIX));
  if (!line) return null;
  try { return JSON.parse(line.slice(TIMING_PREFIX.length).trim()); } catch { return null; }
}
const fmtS = (ms: number) => `${(ms / 1000).toFixed(1)}s`;
function formatTiming(t: { totalMs: number; phases: { phase: string; durationMs: number }[] }): string {
  const steps = t.phases.map((p) => `  • ${fmtS(p.durationMs)}  ${p.phase}`).join("\n");
  return `⏱ timing — total ${fmtS(t.totalMs)} (per phase):\n${steps}`;
}

// Opt-in (SEAM_TIMING=1 on the server env) sub-step breakdown the engine emits as `[build-timing]
// <symbol>: <category> <ms>` lines — splits each grow step into consumer walk+parse vs data-coupling.
// Aggregate by category so a slow grow is attributable; only present when SEAM_TIMING was set.
function parseBuildTiming(stderr: string): string | null {
  const re = /\[build-timing\] .+?: (.+?) (\d+)ms\s*$/;
  const sums = new Map<string, { ms: number; n: number }>();
  for (const l of stderr.split("\n")) {
    const m = re.exec(l); if (!m) continue;
    const s = sums.get(m[1]) ?? { ms: 0, n: 0 }; s.ms += Number(m[2]); s.n += 1; sums.set(m[1], s);
  }
  if (!sums.size) return null;
  const rows = [...sums.entries()].sort((a, b) => b[1].ms - a[1].ms)
    .map(([k, v]) => `  • ${fmtS(v.ms)} total (${v.n}× builds)  ${k}`).join("\n");
  return `🔬 grow sub-steps (SEAM_TIMING):\n${rows}`;
}

// Both content shapes: a JSON block for the agent to parse, a summary for a human to read.
function reply(model: any, stderr = "", notice = "") {
  const timing = parseTiming(stderr);
  const sub = parseBuildTiming(stderr);
  const tail = [timing ? formatTiming(timing) : "", sub ?? ""].filter(Boolean).join("\n\n");
  return { content: [
    { type: "text" as const, text: summarize(model) + notice + (tail ? `\n\n${tail}` : "") },
    { type: "text" as const, text: "```json\n" + JSON.stringify(model) + "\n```" },
  ] };
}

// "This repo was never warmed" nudge. Since interactive grows DON'T learn inline, a cold repo silently
// returns floor-only couplings — the user needs to know cross-framework/event/queue couplings are missing
// until they run warm_adapters ONCE. Fires only when the call WANTED LLM data-coupling (--data-coupling
// llm) AND no `.seam/` adapter cache exists AND this call didn't itself learn — so it stops the moment the
// repo is warmed (warm_adapters writes the cache) and never nags a det/floor query. Repo + intent are read
// from the engine flags so no call site has to thread them.
function warmNudge(baseFlags: string[], model: any): string {
  const dc = baseFlags.indexOf("--data-coupling");
  if (dc < 0 || baseFlags[dc + 1] !== "llm") return "";                 // floor/det query → no learning expected
  if ((model.adapters?.learned ?? []).length > 0) return "";            // this call already learned (e.g. warm_adapters)
  const ri = baseFlags.indexOf("--repo");
  const repo = ri >= 0 ? baseFlags[ri + 1] : null;
  if (!repo) return "";
  const seam = join(repo, ".seam");
  if (existsSync(join(seam, "key-adapters.json")) || existsSync(join(seam, "key-matchers.json"))) return "";   // already warmed
  return "\n\n⚠ Data-coupling not warmed for this repo. Cross-framework / event / queue / cache couplings the "
    + "deterministic floor can't see are NOT in this result yet. Run `warm_adapters({ repo, anchorFile })` ONCE "
    + "(repo-wide, one-time, reused across ALL intents; call until it reports 0 newly learned) — then re-run "
    + "this query and those couplings resolve for free. Until then this used the deterministic floor only.";
}

function errReply(e: unknown) {
  const msg = e instanceof EngineError ? e.message : `unexpected error: ${(e as Error).message}`;
  return { isError: true, content: [{ type: "text" as const, text: msg }] };
}

// One path for every engine: write the seam model to a scratch file and reply with it. `det` runs the
// engine offline in one shot; `hybrid`/`llm` run it over the interactive bridge so its LLM passes are
// served by the caller's own model via sampling.
const PROGRESS_PREFIX = "@@SEAM_PROGRESS@@";   // the engine's per-phase stderr marker (core/progress.ts)

// A per-call stderr handler: mirror EVERY engine line to the log file (so a slow/timed-out call leaves a
// readable trace), and forward each `@@SEAM_PROGRESS@@` phase as an MCP progress notification — which keeps
// a long grow alive past the host's request deadline (the standard keepalive) and is the only signal the
// client gets while the engine works. No-op forwarding when the client didn't send a progressToken.
function engineLineSink(extra: any, callId: string): (line: string) => void {
  const token = extra?._meta?.progressToken;
  let n = 0;
  return (line: string) => {
    log(`${callId}   ${line}`);
    const i = line.indexOf(PROGRESS_PREFIX);
    if (i < 0 || token === undefined || typeof extra?.sendNotification !== "function") return;
    const message = line.slice(i + PROGRESS_PREFIX.length).trim();
    extra.sendNotification({ method: "notifications/progress", params: { progressToken: token, progress: ++n, message } }).catch(() => { /* best-effort */ });
  };
}

// `needsLlm` is true when the run uses ANY LLM pass — a hybrid/llm classifier, OR a det classifier that
// still drives the LLM data-coupling flywheel (so its passes reach the client's model via the bridge, not
// just a local binary). Defaults to "engine isn't det", overridable by the data-coupling flywheel. The
// binary LLM path runs ASYNC (streamed) so the server loop isn't frozen for the whole grow — that freeze is
// what made a heavy grow_intent time out at the host: spawnSync blocked progress + the keep-alive entirely.
async function decompose(server: McpServer, baseFlags: string[], engine: string, needsLlm = engine !== "det", extra?: any, extraEnv?: Record<string, string>) {
  return withScratch(async (scratch) => {
    const out = join(scratch, "seams.json");
    const flags = [...baseFlags, "--classifier", engine, "--emit-seams", out];
    const callId = nextCallId();
    const t0 = Date.now();
    const sink = engineLineSink(extra, callId);
    log(`${callId} ▶ engine ${needsLlm ? "(llm)" : "(det)"}: ${flags.join(" ")}`);
    let stderr = "";
    try {
      if (!needsLlm) stderr = runEngine(flags, undefined, extraEnv).stderr;                              // offline, fast, sync
      else if (resolveLlmServe(server) === "binary") stderr = (await runEngineAsync(flags, sink, undefined, extraEnv)).stderr;   // claude/copilot, streamed
      else stderr = await runEngineWithBridge(server, flags, scratch, sink, extraEnv);    // borrow the client's model via sampling
      log(`${callId} ✓ done in ${Date.now() - t0}ms`);
    } catch (e) {
      log(`${callId} ✗ failed after ${Date.now() - t0}ms: ${(e as Error).message}`);
      throw e;
    }
    const model = readJson(out);
    return reply(model, stderr, warmNudge(baseFlags, model));
  });
}

