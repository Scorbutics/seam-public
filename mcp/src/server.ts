// Seam MCP server — lets ANY LLM agent consult Seam about a diff or an intent footprint, over the
// same --emit-seams JSON contract the VS Code extension consumes. Thin by design: it locates the
// stateless engine (binary or source CLI) and shells out per call. No daemon, no engine state.
//
// Two reaches for the LLM passes:
//   • engine="det"  → fully offline, no model at all. The robust default; most agents want the
//                     STRUCTURE (seams/roles/wiring), not Seam's own prose.
//   • engine="hybrid"/"llm" → borrows the CALLING client's model via MCP sampling (see sampling.ts).
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";
import { join } from "node:path";
import { EngineError, backendKind, readJson, runEngine, withScratch, writeText } from "./engine.js";
import { clientSupportsSampling, runEngineWithBridge } from "./sampling.js";

// How the LLM passes of hybrid/llm engines are served:
//   binary   → the engine makes its OWN calls via a local claude/copilot binary (cheap dedicated tier,
//              thinking-off, no sampling needed — works on clients like Copilot that lack MCP sampling)
//   sampling → borrow the CALLING client's model via MCP sampling (no local binary needed)
//   auto     → prefer a local binary when one resolves, else fall back to sampling (default)
// Override with SEAM_MCP_LLM. The catch: a binary uses ITS model, not the caller's — set "sampling" if
// you specifically want the seam-intent labels generated by the same model the agent is using.
type LlmServe = "binary" | "sampling";
const LLM_MODE = (process.env.SEAM_MCP_LLM ?? "auto").toLowerCase();

// Resolve, per call, how to serve LLM passes — throwing a precise, actionable error when neither path
// is available (so a Copilot user without sampling gets "put a binary on PATH", not a silent failure).
function resolveLlmServe(server: McpServer): LlmServe {
  if (LLM_MODE === "binary") return "binary";
  if (LLM_MODE === "sampling") return "sampling";
  if (backendKind()) return "binary";               // auto: a local claude/copilot wins
  if (clientSupportsSampling(server)) return "sampling";
  throw new EngineError(
    "this engine setting needs LLM passes, but no way to serve them is available: no local "
    + "claude/copilot binary resolved (set CLAUDE_BIN / COPILOT_BIN or put one on PATH) AND this MCP "
    + "client does not support sampling. Use engine=\"det\" for a fully offline footprint instead.");
}

const ENGINE = z.enum(["det", "hybrid", "llm"]).default("det")
  .describe("det = offline, no LLM (default, recommended). hybrid/llm add product-intent labels via a "
    + "local claude/copilot binary if present, else YOUR model over MCP sampling (SEAM_MCP_LLM overrides).");

// Opt-in LLM data-coupling (--data-coupling llm). The deterministic floor already couples DB tables,
// HTTP routes (incl. annotation handlers ⇄ fetch/$http callers), and edge functions across the stack.
// FALLBACK-gated: the LLM key pass fires only on nodes the floor couldn't key, bounded by a per-run
// budget — so it scales on a heavy grow (the floor covers the bulk for free). Turn it ON when a question
// genuinely SPANS frameworks/stacks and the trace left a cross-stack blindspot; off by default.
const CROSS_FRAMEWORK = z.boolean().default(false)
  .describe("Enable LLM cross-framework data-coupling. Fallback-gated (an LLM pass only on nodes the "
    + "deterministic floor couldn't key, budget-capped). Use when the question spans frameworks/stacks "
    + "AND the deterministic trace left a blindspot; off by default.");

// A compact human-facing summary so a chat client shows something legible above the JSON.
function summarize(model: any): string {
  const clusters = model.clusters ?? [];
  const seams = clusters.reduce((n: number, c: any) => n + (c.seams?.length ?? 0), 0);
  const roleCounts: Record<string, number> = {};
  for (const c of clusters) for (const s of c.seams ?? []) for (const h of s.hunks ?? [])
    roleCounts[h.role] = (roleCounts[h.role] ?? 0) + 1;
  for (const h of [...(model.tests ?? []), ...(model.noise ?? [])]) roleCounts[h.role] = (roleCounts[h.role] ?? 0) + 1;
  const roles = Object.entries(roleCounts).map(([r, n]) => `${r}=${n}`).join("  ");
  const intents = clusters.map((c: any) => `• ${c.intent}`).join("\n");
  const head = `${clusters.length} cluster(s), ${seams} seam(s)   [${roles}]`;
  const extras = [
    model.mode ? `mode=${model.mode}` : "",
    model.anchor ? `anchor=${model.anchor}` : "",
    model.resolutionQuality ? `resolution=${model.resolutionQuality}` : "",
    model.usage ? `${model.usage.calls} LLM call(s)` : "",
  ].filter(Boolean).join("  ");
  return `${head}${extras ? `   (${extras})` : ""}\n${intents}`;
}

// The engine emits a one-line timing summary on stderr at the end of a run (see core/progress.ts).
// Parse it so the agent can tell the user how long each phase took. Contract marker — keep in sync.
const TIMING_PREFIX = "@@SEAM_TIMING@@";
function parseTiming(stderr: string): { totalMs: number; phases: { phase: string; durationMs: number }[] } | null {
  const line = stderr.split("\n").reverse().find((l) => l.startsWith(TIMING_PREFIX));
  if (!line) return null;
  try { return JSON.parse(line.slice(TIMING_PREFIX.length).trim()); } catch { return null; }
}
const fmtS = (ms: number) => `${(ms / 1000).toFixed(1)}s`;
function formatTiming(t: { totalMs: number; phases: { phase: string; durationMs: number }[] }): string {
  const steps = t.phases.map((p) => `  • ${fmtS(p.durationMs)}  ${p.phase}`).join("\n");
  return `⏱ timing — total ${fmtS(t.totalMs)} (per phase):\n${steps}`;
}

// Opt-in (SEAM_TIMING=1 on the server env) sub-step breakdown the engine emits as `[build-timing]
// <symbol>: <category> <ms>` lines — splits each grow step into consumer walk+parse vs data-coupling.
// Aggregate by category so a slow grow is attributable; only present when SEAM_TIMING was set.
function parseBuildTiming(stderr: string): string | null {
  const re = /\[build-timing\] .+?: (.+?) (\d+)ms\s*$/;
  const sums = new Map<string, { ms: number; n: number }>();
  for (const l of stderr.split("\n")) {
    const m = re.exec(l); if (!m) continue;
    const s = sums.get(m[1]) ?? { ms: 0, n: 0 }; s.ms += Number(m[2]); s.n += 1; sums.set(m[1], s);
  }
  if (!sums.size) return null;
  const rows = [...sums.entries()].sort((a, b) => b[1].ms - a[1].ms)
    .map(([k, v]) => `  • ${fmtS(v.ms)} total (${v.n}× builds)  ${k}`).join("\n");
  return `🔬 grow sub-steps (SEAM_TIMING):\n${rows}`;
}

// Both content shapes: a JSON block for the agent to parse, a summary for a human to read.
function reply(model: any, stderr = "") {
  const timing = parseTiming(stderr);
  const sub = parseBuildTiming(stderr);
  const tail = [timing ? formatTiming(timing) : "", sub ?? ""].filter(Boolean).join("\n\n");
  return { content: [
    { type: "text" as const, text: summarize(model) + (tail ? `\n\n${tail}` : "") },
    { type: "text" as const, text: "```json\n" + JSON.stringify(model) + "\n```" },
  ] };
}

function errReply(e: unknown) {
  const msg = e instanceof EngineError ? e.message : `unexpected error: ${(e as Error).message}`;
  return { isError: true, content: [{ type: "text" as const, text: msg }] };
}

// One path for every engine: write the seam model to a scratch file and reply with it. `det` runs the
// engine offline in one shot; `hybrid`/`llm` run it over the interactive bridge so its LLM passes are
// served by the caller's own model via sampling.
async function decompose(server: McpServer, baseFlags: string[], engine: string) {
  return withScratch(async (scratch) => {
    const out = join(scratch, "seams.json");
    const flags = [...baseFlags, "--classifier", engine, "--emit-seams", out];
    let stderr = "";
    if (engine === "det") stderr = runEngine(flags).stderr;                       // offline, no LLM
    else if (resolveLlmServe(server) === "binary") stderr = runEngine(flags).stderr;   // engine serves its own passes via claude/copilot
    else await runEngineWithBridge(server, flags, scratch);       // borrow the client's model via sampling
    return reply(readJson(out), stderr);
  });
}

const server = new McpServer(
  { name: "seam", version: "0.1.0" },
  { instructions:
      "Seam decomposes a code change (or a codebase footprint around an anchor) into review SEAMS — "
      + "units of one intent — labelling each hunk core/link/environment/test/noise with wiring. Use "
      + "`decompose_diff` to understand what a diff actually does and how to review it by intent; use "
      + "`intent_footprint` to map where a symbol/intent lives across a codebase. Default engine 'det' "
      + "is offline and instant; 'hybrid'/'llm' add product-intent labels via a local claude/copilot "
      + "binary when present, else YOUR model over MCP sampling." },
);

server.registerTool("decompose_diff", {
  title: "Decompose a diff into review seams",
  description:
    "Group a git diff into seams (one technical intent each), labelling every hunk by role "
    + "(core/link/environment/test/noise) with wiring and optional blast-radius. Pass `diff` (raw "
    + "unified-diff text) OR `repo`+`range` (a git revision range like 'HEAD~1' or 'main...HEAD'). "
    + "Returns the Seam JSON model (docs/SEAM_JSON_CONTRACT.md). Roles top out ~0.8 accuracy and "
    + "confidence<0.6 means 'maybe' — the tool structures, the human judges. "
    + "WHEN: to review a diff/PR by intent (core/link/env/test), not file-by-file. This is not a search "
    + "tool — it explains a change you ALREADY have.",
  inputSchema: {
    diff: z.string().optional().describe("Raw unified-diff text. Provide this OR repo+range."),
    repo: z.string().optional().describe("Absolute path to the git repo (with `range`)."),
    range: z.string().optional().describe("Git revision range, e.g. 'HEAD~1', 'main...HEAD'."),
    engine: ENGINE,
    blastRadius: z.boolean().default(false).describe("Also find files OUTSIDE the diff that import changed symbols."),
  },
}, async ({ diff, repo, range, engine, blastRadius }) => {
  try {
    if (!diff && !(repo && range))
      return errReply(new EngineError("provide `diff` (raw diff text) or both `repo` and `range`."));
    return await withScratch(async (scratch) => {
      const base: string[] = [];
      if (diff) { const p = join(scratch, "change.patch"); writeText(p, diff); base.push("--file", p); }
      else base.push("--git", range!);
      if (repo) base.push("--repo", repo);   // required for --git; with `diff` it enables resolved wiring / blast-radius
      if (blastRadius) base.push("--blast-radius");
      return await decompose(server, base, engine);
    });
  } catch (e) { return errReply(e); }
});

server.registerTool("intent_footprint", {
  title: "Map an intent's footprint across a codebase",
  description:
    "Starting from an ANCHOR (a symbol, or a whole module file), trace its footprint across the "
    + "codebase and decompose it into seams — who consumes it, what it wires, where the intent lives. "
    + "Honest about gaps: statically-opaque edges are returned as SUGGESTED/blindspots, never asserted. "
    + "Returns the Seam JSON model with codebase-mode fields (resolutionQuality, unresolved, blindspots). "
    + "WHEN: you KNOW the anchor symbol/file and want its footprint + consumers. For 'how does X work/flow' "
    + "WITHOUT a known anchor, use `grow_intent`. NOT for a single symbol lookup or find-usages — grep/LSP "
    + "is instant; reach here only when you need the traced cross-file footprint, not a list of locations. "
    + "COMPOSE across boundaries: when the footprint ends at a cross-stack blindspot (a shared key/route "
    + "whose other side isn't here — e.g. a backend→frontend data flow), call this tool AGAIN anchored on "
    + "the other side (the key as `intent`, or the consumer file as `anchorFile`) and stitch the two "
    + "footprints together — don't degrade to a manual grep sweep.",
  inputSchema: {
    repo: z.string().describe("Absolute path to the git repo."),
    anchorFile: z.string().describe("Path to the file holding the anchor symbol/module (relative to repo or absolute)."),
    symbol: z.string().optional().describe("The anchor symbol. Omit to analyze the whole module (all its exports)."),
    intent: z.string().optional().describe("A natural-language intent to focus the footprint on (hybrid/llm engines)."),
    depth: z.number().int().min(1).max(4).default(1).describe("How many consumer hops to follow."),
    crossFramework: CROSS_FRAMEWORK,
    engine: ENGINE,
  },
}, async ({ repo, anchorFile, symbol, intent, depth, crossFramework, engine }) => {
  try {
    const base = ["--scan", "--repo", repo, "--anchor-file", anchorFile, "--depth", String(depth)];
    if (symbol) base.push("--symbol", symbol);
    if (intent) base.push("--intent", intent);
    if (crossFramework) base.push("--data-coupling", "llm");
    return await decompose(server, base, engine);
  } catch (e) { return errReply(e); }
});

// Auto-grow: the LLM-in-the-loop counterpart to intent_footprint. Where intent_footprint takes ONE
// static scan, this LOOPS — the model repeatedly picks the next node/direction to follow toward the
// question, the engine expands the footprint, and it decomposes the grown result. Every move + the
// final decomposition are served by YOUR model via sampling, so it is LLM-only (no `det`).
const LLM_ENGINE = z.enum(["hybrid", "llm"]).default("hybrid")
  .describe("LLM engine, served by a local claude/copilot binary if present, else YOUR model via "
    + "sampling. 'det' is not valid for auto-grow.");

server.registerTool("grow_intent", {
  title: "Grow an intent footprint across a codebase (LLM-directed)",
  description:
    "Answer a question about a codebase by GROWING a footprint toward it: seed from an anchor symbol, "
    + "then let the model iteratively choose the next consumer (up) or dependency (down) to follow until "
    + "the footprint covers the answer, and decompose the result into seams. This is Seam's "
    + "auto-orchestration loop — the model directs every move, served by a local claude/copilot binary "
    + "when present (cheap dedicated tier), else YOUR model over MCP sampling. So it works WITHOUT a "
    + "sampling-capable client as long as a claude/copilot CLI is on PATH. For a single non-iterative "
    + "scan, use `intent_footprint` instead. "
    + "WHEN TO CALL: the question is how a feature / intent / mechanism WORKS or FLOWS across multiple "
    + "files and you need the ordered path (anchor → … → where it culminates) — prefer ONE call here over "
    + "4+ iterative greps to stitch a flow by hand, and call it to MAP a flow before editing across it. "
    + "Do NOT use for naming a known symbol, find-usages, or a single-fact lookup — grep/LSP is faster. "
    + "Returns `noFlow` when the intent is computation/strategy with no traceable spine. "
    + "COMPOSE across boundaries: when the grown footprint ends at a cross-stack blindspot (a shared "
    + "key/route whose other side isn't in this footprint — e.g. backend→frontend), call this tool AGAIN "
    + "anchored on the OTHER side (the key as `intent`) and stitch the two together, instead of grepping. "
    + "PASS THE ANCHOR YOU ALREADY HAVE: `symbol` is the starting point — when you've already located a "
    + "likely symbol (you usually have, from a couple of orienting greps/reads), give it here and Seam "
    + "traces+decomposes from it directly (~11s) instead of hunting for the anchor itself (~28s). So the "
    + "efficient pattern is: grep to ORIENT (find one candidate), then this tool to TRACE from it. "
    + "ALSO a PLANNING step before implementing: before changing a flow you haven't mapped — when "
    + "understanding the current code would take 2+ symbol-discovery greps across files — call this FIRST "
    + "to plan against a verified spine + blast-radius, not a guess; cheaper than reconstructing it yourself.",
  inputSchema: {
    repo: z.string().describe("Absolute path to the git repo."),
    anchorFile: z.string().describe("Path to the file holding the anchor symbol (relative to repo or absolute)."),
    symbol: z.string().describe("The anchor symbol to seed the footprint from."),
    intent: z.string().describe("The natural-language question to grow the footprint toward."),
    maxSteps: z.number().int().min(1).max(8).default(4).describe("Maximum number of grow moves the model may make."),
    crossFramework: CROSS_FRAMEWORK,
    engine: LLM_ENGINE,
  },
}, async ({ repo, anchorFile, symbol, intent, maxSteps, crossFramework, engine }) => {
  try {
    const base = ["--scan", "--auto", "--repo", repo, "--anchor-file", anchorFile,
      "--symbol", symbol, "--intent", intent, "--max-steps", String(maxSteps)];
    if (crossFramework) base.push("--data-coupling", "llm");
    return await decompose(server, base, engine);
  } catch (e) { return errReply(e); }
});

async function main() {
  const transport = new StdioServerTransport();
  await server.connect(transport);
  process.stderr.write("seam-mcp: ready on stdio\n");
}

main().catch((e) => { process.stderr.write(`seam-mcp: fatal: ${e?.stack ?? e}\n`); process.exit(1); });
